#!/usr/bin/env node
/**
 * Writes .env from linked Supabase project (CLI must be logged in + linked).
 * Usage: node scripts/setup-supabase-env.mjs [database-password]
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const PROJECT_REF = "nynbxynddxxevkcsuuog";
const REGION = "ap-south-1";

function sh(cmd) {
  return execSync(cmd, { encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] }).trim();
}

const keysJson = sh(
  `supabase projects api-keys --project-ref ${PROJECT_REF} -o json`,
);
const keys = JSON.parse(keysJson);
const anon = keys.find((k) => k.name === "anon")?.api_key;
if (!anon) throw new Error("Could not read Supabase anon key");

const password = process.argv[2];
if (!password) {
  console.error(
    "Usage: node scripts/setup-supabase-env.mjs <database-password>\n" +
      "Password: Supabase Dashboard → Project Settings → Database → Database password",
  );
  process.exit(1);
}

const authSecret = randomBytes(32).toString("base64");
const databaseUrl = `postgresql://postgres.${PROJECT_REF}:${encodeURIComponent(password)}@aws-0-${REGION}.pooler.supabase.com:6543/postgres?pgbouncer=true`;

const env = `# Generated by scripts/setup-supabase-env.mjs
DATABASE_URL="${databaseUrl}"
NEXT_PUBLIC_SUPABASE_URL="https://${PROJECT_REF}.supabase.co"
NEXT_PUBLIC_SUPABASE_ANON_KEY="${anon}"
AUTH_SECRET="${authSecret}"
`;

writeFileSync(".env", env);
console.log("Wrote .env for Supabase project navigator_app");
